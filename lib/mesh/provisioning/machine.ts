/**
 * The provisioning state machine (Mesh Protocol v1.1, Section 5.4.2
 * "Provisioning behavior"): the PROVISIONER side only - this project's
 * design (docs/superpowers/specs/2026-10-06-ble-mesh-provisioner-design.md
 * in the homtelli project) has Homey provision bulbs, never be provisioned
 * itself, so there is no Provisionee half to build here. This module
 * decides which Provisioning PDU to send next, verifies the two the peer
 * sends back that this side can actually check (Public Key, Confirmation,
 * Random), and builds the final Provisioning Data block - it does not
 * transport bytes (that is the adapter's "transport" port, per the design
 * document) and it does not decide network/application keys or unicast
 * addresses (that is the caller's allocator); it only drives the exchange
 * using whatever the caller already decided and already generated.
 *
 * SCOPE: the no-OOB path only, same commitment `pdu.ts` already states.
 * Algorithm is always BTM_ECDH_P256_CMAC_AES128_AES_CCM (Table 5.29 value
 * 0x00) - the only one `provisioning/crypto.ts` implements - Authentication
 * Method is always No OOB (Table 5.31 value 0x00), and AuthValue is always
 * the fixed 128-bit all-zero value Section 5.4.2.4.1 defines for that
 * method ("the authentication value shall be set to
 * 0x00000000000000000000000000000000, which means it is not
 * authenticated"). A device whose Capabilities PDU cannot be satisfied by
 * this (Section 5.4.2.3's own rule, see `MANDATORY OOB REFUSAL` below, or a
 * device that does not even offer the one algorithm this project
 * implements) is reported as `'unsupported'`, never silently treated as
 * though it had asked for the no-OOB path it did not actually offer.
 *
 * PURITY. Like `packet/reassembly.ts`, this module keeps nothing of its
 * own: no module-level binding, no timer, no clock, and - unlike a real
 * Provisioner - no random number generator either. The ephemeral ECDH key
 * pair and RandomProvisioner (Section 5.4.2.4.1: "a string of random bits
 * generated by the Provisioner's random number generator ... compatible
 * with the requirements in Volume 2, Part H, Section 2 of the Core
 * Specification") are INPUTS to `beginProvisioning`, supplied by the
 * caller, not generated here. This is not only for purity: it is what
 * makes the published Section 8.7/8.17.1 exchange replayable as a
 * known-answer test at all, because the sample fixes both values, and a
 * module that rolled its own randomness could only ever be tested against
 * itself.
 *
 * ONE NULLISH CONVENTION, same reasoning as `packet/reassembly.ts`'s own
 * header: there is no `null`/`undefined` anywhere in this module's own
 * surface. Every `ProvisioningState` - including the three terminal
 * phases, `'provisioned'`/`'unsupported'`/`'failed'` - is a concrete,
 * fully-formed value, and `step` accepts every phase its own return type
 * can produce, so a caller can always feed a previous result's `state`
 * straight back in without an adapter in between:
 *
 *     let { state, send } = beginProvisioning(input);
 *     // ... send `send` over the transport, wait for a reply ...
 *     ({ state, send } = step(state, replyBytes));
 *
 * `step` on a terminal state (`'provisioned'`/`'unsupported'`/`'failed'`)
 * is a deliberate no-op - the same `state` comes back unchanged and
 * `send` is empty - rather than a throw, because "the exchange already
 * ended" is foreseeable, ordinary caller behaviour (a transport adapter
 * that races a stray retransmission against the bearer closing, for
 * instance), not a programming mistake.
 *
 * DIRECTION AND ORDER (`pdu.ts`'s own module header transcribes this in
 * full; repeated here only as the one-line map this module's `step`
 * dispatch follows): Invite(P->D), Capabilities(D->P), Start(P->D), Public
 * Key(P->D then D->P), Confirmation(P->D then D->P), Random(P->D then
 * D->P), Data(P->D), Complete(D->P) - with a Failed PDU (D->P) able to
 * replace whatever the Provisionee was about to send, at any point.
 * `beginProvisioning` sends Invite; every other P->D send happens inside
 * `step`, triggered by the D->P PDU immediately before it in this order -
 * EXCEPT Start and Public Key(Provisioner), which Section 5.4.2.3 has the
 * Provisioner send back-to-back with no reply in between ("Once the
 * Provisioner has determined it can provision the Provisionee, it shall
 * send a ... Start PDU" immediately followed by "a new key pair shall be
 * generated by the Provisioner ... and the public key ... shall be
 * transmitted"), so the single `step` call that processes the incoming
 * Capabilities PDU returns BOTH in its `send` array, in that order. This
 * is the one point in the exchange where `send` holds more than one PDU;
 * `beginProvisioning`'s own `Figure 5.15` prose ("Provisioning is
 * performed using a five-step process: beaconing, invitation, exchanging
 * public keys, authentication, and distribution of the provisioning
 * data") groups them the same way.
 *
 * WHAT MAKES A STEP FAIL, failure PDUs and reason codes (Section 5.4.4
 * "Provisioning errors", Table 5.41 "Provisioning error codes"): "When the
 * provisioning protocol fails for any reason, the Provisionee shall
 * permanently delete any stored details ... The provisioning protocol is
 * asymmetric when handling protocol errors. When the Provisioner
 * encounters an error other than a timeout in the provisioning protocol,
 * it shall immediately disconnect the provisioning bearer, providing the
 * Fail reason." The PROVISIONER never sends a Provisioning Failed PDU
 * (`pdu.ts`'s own DIRECTION table: Failed is Provisionee -> Provisioner
 * only) - so a `'failed'` result from THIS module is never itself a wire
 * message; it is this module's own classification of why it is refusing
 * to continue, using Table 5.41's own named vocabulary (`errorCode` plus
 * `errorName`, via `provisioningErrorName` below) because that vocabulary
 * is what the specification already uses for exactly these conditions,
 * not because the Provisioner transmits it. Three sources feed a
 * `'failed'` result:
 *
 *   1. The Provisionee's OWN Provisioning Failed PDU, reporting ITS error
 *      code verbatim (Section 5.4.1.10: "sent instead of the next
 *      expected PDU at any point once something goes wrong") - checked
 *      FIRST, before any phase-specific type check, in every handler
 *      below, because a Failed PDU is always a valid thing to receive,
 *      never itself "unexpected".
 *   2. A PDU this module cannot even decode, or one that decodes but is
 *      not the type this phase expects - classified 0x01 "Invalid PDU" or
 *      0x03 "Unexpected PDU" respectively (see `decodeOrFail`/
 *      `unexpectedType` below). THIS is the "PDU arriving out of order"
 *      case: Section 5.4.4's asymmetric handling means the Provisioner's
 *      own answer to it is exactly the same as any other protocol error -
 *      stop, with a reason - not silently wait for the right PDU to show
 *      up later, which would leave a caller unable to tell a slow-but-
 *      healthy peer from one that has already gone wrong.
 *   3. A cryptographic check this module performs itself failing: an
 *      invalid or degenerate device public key (0x02 "Invalid Format",
 *      Section 5.4.2.3: "When the Provisioner receives an invalid public
 *      key or a public key that is equal to the Provisioner public key,
 *      then provisioning shall fail"), or a confirmation value that does
 *      not check out (0x04 "Confirmation Failed", Section 5.4.2.4.2 - two
 *      separate checks share this code: the one described below and the
 *      main one, `onRandomDevice`'s own recomputation).
 *
 * Section 5.4.2.4.2 also documents a cheap SANITY check this module
 * performs before anything else, once the Provisionee's Confirmation PDU
 * arrives: "the Provisioner ... shall compare the ConfirmationProvisioner
 * and the ConfirmationDevice values. If the values are equal, the
 * provisioning protocol shall fail" - i.e. if the value just received is
 * byte-identical to the value THIS side already sent, something is badly
 * wrong (a reflection, or a peer that never used its own random number),
 * and this is cheap enough to check immediately rather than only
 * discovering it indirectly once RandomDevice fails to reproduce it.
 *
 * MANDATORY OOB REFUSAL (Section 5.4.2.3): "If bit 1 of the OOB Type
 * field of the Provisioning Capabilities PDU is set to 1 (Only OOB
 * authenticated provisioning supported) and any of the following
 * conditions is met: the Algorithm field ... is not set to
 * BTM_ECDH_P256_CMAC_AES128_AES_CCM and ... Authentication Method field
 * set to ... No OOB [or] the Algorithm field is set to
 * BTM_ECDH_P256_CMAC_AES128_AES_CCM [at all] ... the provisioning
 * protocol shall fail". Read together, a device with that bit set can
 * never legally be provisioned using BTM_ECDH_P256_CMAC_AES128_AES_CCM -
 * the only algorithm this project implements - regardless of
 * Authentication Method, so this module refuses as soon as it sees that
 * bit, before ever building a Start PDU. This is `'unsupported'`, not
 * `'failed'`: nothing has been sent, no protocol error has occurred, and
 * the design document is explicit that this is an open product decision
 * ("the wizard reports this and we decide later whether to add that
 * path"), not a defect - "it must not be silently treated as the no-OOB
 * case" is the brief's own wording for why this gets its own phase rather
 * than being folded into `'failed'`. The same `'unsupported'` phase (with
 * a different `reason`) also covers a device whose Capabilities PDU does
 * not offer BTM_ECDH_P256_CMAC_AES128_AES_CCM at all (Table 5.21 bit 0
 * clear) - this project has no other algorithm to fall back to (see
 * `provisioning/crypto.ts`'s own header), so that device cannot be
 * provisioned by this module either, for a different, equally mundane
 * reason.
 *
 * PROVISIONING DATA FIELD ENCODING (Section 5.4.2.5, Table 5.47
 * "Provisioning data format": Network Key (16) || Key Index (2) || Flags
 * (1) || IV Index (4) || Unicast Address (2), 25 octets total). Key
 * Index, IV Index and Unicast Address are encoded here as plain
 * big-endian multi-octet numeric values, per Section 3.1.1's general rule
 * for Provisioning ("For ... Provisioning, all multiple-octet numeric
 * values shall be sent in big-endian" - the same rule `pdu.ts` already
 * applies to the Provisioning PDU layer's own numeric fields) - NOT
 * Section 4.3.1.1's Figure 4.4/4.5 bit-packed key-index format, even
 * though Table 5.47's own Key Index row text cross-references that
 * section. That packed format requires the second octet's top nibble to
 * be zero ("the 4 MSbs of the second octet shall be set to 0"), and the
 * published Section 8.7.12/8.17.1 sample's own Key Index bytes (`05 67`)
 * do not satisfy that - the second octet's top nibble is `0x6` - while
 * they ARE exactly consistent with a plain big-endian 16-bit value
 * (`0x0567`, whose top nibble is naturally `0` for any value inside the
 * 12-bit range Section 4.3.1.1 says global key indexes occupy). Figure
 * 4.4/4.5's bit-packing applies to packing MULTIPLE key indexes
 * compactly (its own text: "two key indexes are packed into three
 * octets"); Table 5.47 allocates Key Index its own full two-octet field
 * with nothing else packed alongside it, so the general Section 3.1.1
 * rule - not the multi-index packing recipe - is what the sample's own
 * bytes are measured here to actually follow. `MAX_KEY_INDEX` below still
 * enforces the 12-bit domain limit Section 4.3.1.1 states, independent of
 * which encoding is used.
 */

