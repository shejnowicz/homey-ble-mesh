/** The ephemeral P-256 key pair this provisioning attempt uses - generated and owned by the caller (see the module header's PURITY note), matching `crypto/ecdh.ts#generateKeyPair`'s own return shape. */
export interface EphemeralKeyPair {
  readonly publicKey: Buffer;
  readonly privateKey: Buffer;
}

/** Table 5.47 "Provisioning data format" - the network membership this provisioning attempt hands to the new node, decided entirely by the caller (this module owns no key material, address allocator or network state of its own). */
export interface ProvisioningDataInput {
  /** NetKey, 16 octets. */
  readonly netKey: Buffer;
  /** Global NetKey Index, 12 bits (Section 4.3.1.1). */
  readonly netKeyIndex: number;
  /** Table 5.48 bitmask: bit 0 Key Refresh Flag, bit 1 IV Update Flag, bits 2-7 RFU. */
  readonly flags: number;
  /** Current IV Index, 32 bits. */
  readonly ivIndex: number;
  /** Unicast address to assign to the new node's primary element. */
  readonly unicastAddress: number;
}

/** `beginProvisioning`'s input: everything needed to send the first PDU (Invite) and to carry the exchange through to Provisioning Data, all caller-supplied per the module header's PURITY note. */
export interface BeginProvisioningInput {
  /** Provisioning Invite PDU's Attention Duration field, seconds (Table 5.18). */
  readonly attentionDuration: number;
  readonly ephemeralKeyPair: EphemeralKeyPair;
  /** RandomProvisioner (Section 5.4.2.4.1), 16 bytes. */
  readonly randomProvisioner: Buffer;
  readonly provisioningData: ProvisioningDataInput;
}

