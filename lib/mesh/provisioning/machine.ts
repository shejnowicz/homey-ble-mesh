/**
 * The caller-owned state value (see the module header's PURITY and ONE
 * NULLISH CONVENTION notes). `phase` is the discriminant; the three
 * terminal phases (`'provisioned'`, `'unsupported'`, `'failed'`) carry no
 * leftover key material or other secrets from earlier phases - once the
 * exchange is decided, there is nothing further for this module to do
 * with them.
 */
export type ProvisioningState =
  | AwaitingCapabilitiesState
  | AwaitingPublicKeyDeviceState
  | AwaitingConfirmationDeviceState
  | AwaitingRandomDeviceState
  | AwaitingCompleteState
  | ProvisionedState
  | UnsupportedState
  | FailedState;

/**
 * Both `beginProvisioning` and `step` return this same shape: the next
 * state, plus every PDU (wire bytes, ready for the transport port) this
 * side must now send, in order. `send` is most often one element; it is
 * two only for the Capabilities step (see the module header's DIRECTION
 * AND ORDER note) and empty for every terminal phase.
 */
export interface ProvisioningStepResult {
  readonly state: ProvisioningState;
  readonly send: readonly Buffer[];
}

// ===========================================================================
// Input validation helpers (caller mistakes - thrown, never a `'failed'`
// result; see `pdu.ts`/`crypto.ts`'s own helpers of the same shape).
// ===========================================================================

function assertBufferLength(field: string, value: Buffer, expected: number): void {
  if (value.length !== expected) {
    throw new Error(`provisioning machine field "${field}" must be ${expected} bytes, got ${value.length}`);
  }
}

// ===========================================================================
// Shared result builders.
// ===========================================================================

function makeFailed(errorCode: number, reason: string): FailedState {
  return { phase: 'failed', errorCode, errorName: provisioningErrorName(errorCode), reason };
}

function unexpectedType(expectedLabel: string, actualType: string): FailedState {
  return makeFailed(0x03, `expected a ${expectedLabel} PDU but received a ${actualType} PDU`);
}

type DecodeOutcome = { readonly decoded: ProvisioningPdu } | { readonly failed: FailedState };

/**
 * Shared by every phase handler: decodes `pdu` and, before any
 * phase-specific type check, handles the two conditions that are never
 * "unexpected" no matter which phase this is (see the module header's
 * WHAT MAKES A STEP FAIL note, source 1 and the decode half of source 2) -
 * a Provisioning Failed PDU from the device, reported verbatim, and bytes
 * this project's codec cannot decode at all.
 */
function decodeOrFail(pdu: Buffer): DecodeOutcome {
  const decoded = decodeProvisioningPdu(pdu);
  if (decoded === null) {
    return {
      failed: makeFailed(
        0x01,
        'received bytes do not decode as a recognised Provisioning PDU (wrong length, non-zero Padding bits, or an unimplemented/unassigned Type)',
      ),
    };
  }
  if (decoded.type === 'failed') {
    const name = provisioningErrorName(decoded.errorCode);
    return {
      failed: makeFailed(
        decoded.errorCode,
        `device reported provisioning failure: ${name} (0x${decoded.errorCode.toString(16).padStart(2, '0')})`,
      ),
    };
  }
  return { decoded };
}

// ===========================================================================
// Provisioning Data field encoding (Table 5.47 - see the module header's
// PROVISIONING DATA FIELD ENCODING note).
// ===========================================================================

function encodeUInt16BE(value: number): Buffer {
  const buf = Buffer.alloc(2);
  buf.writeUInt16BE(value, 0);
  return buf;
}

function encodeUInt32BE(value: number): Buffer {
  const buf = Buffer.alloc(4);
  buf.writeUInt32BE(value, 0);
  return buf;
}

// ===========================================================================
// beginProvisioning: sends Invite, the exchange's one send with no
// incoming PDU to react to.
// ===========================================================================

export function beginProvisioning(input: BeginProvisioningInput): ProvisioningStepResult {
  assertRange('provisioning machine field "attentionDuration"', input.attentionDuration, MAX_OCTET);
  assertBufferLength('ephemeralKeyPair.publicKey', input.ephemeralKeyPair.publicKey, PUBLIC_KEY_LENGTH);
  assertBufferLength('ephemeralKeyPair.privateKey', input.ephemeralKeyPair.privateKey, PRIVATE_KEY_LENGTH);
  assertBufferLength('randomProvisioner', input.randomProvisioner, RANDOM_LENGTH);
  assertBufferLength('provisioningData.netKey', input.provisioningData.netKey, NET_KEY_LENGTH);
  assertRange('provisioning machine field "provisioningData.netKeyIndex"', input.provisioningData.netKeyIndex, MAX_KEY_INDEX);
  assertRange('provisioning machine field "provisioningData.flags"', input.provisioningData.flags, MAX_OCTET);
  assertRange('provisioning machine field "provisioningData.ivIndex"', input.provisioningData.ivIndex, MAX_IV_INDEX);
  assertRange('provisioning machine field "provisioningData.unicastAddress"', input.provisioningData.unicastAddress, MAX_ADDRESS);

  const invitePdu: ProvisioningInvite = { type: 'invite', attentionDuration: input.attentionDuration };
  const inviteBytes = encodeProvisioningPdu(invitePdu);

  const state: ProvisioningState = {
    phase: 'awaitingCapabilities',
    inviteValue: inviteBytes.subarray(1), // Parameters only - Section 5.4.2.4.1's "...PDUValue" excludes the Type octet.
    ephemeralKeyPair: input.ephemeralKeyPair,
    randomProvisioner: input.randomProvisioner,
    provisioningData: input.provisioningData,
  };
  return { state, send: [inviteBytes] };
}

// ===========================================================================
// step: dispatches to the phase-specific handler, or no-ops on a terminal
// phase (see the module header's ONE NULLISH CONVENTION note).
// ===========================================================================

export function step(state: ProvisioningState, pdu: Buffer): ProvisioningStepResult {
  switch (state.phase) {
    case 'awaitingCapabilities':
      return onCapabilities(state, pdu);
    case 'awaitingPublicKeyDevice':
      return onPublicKeyDevice(state, pdu);
    case 'awaitingConfirmationDevice':
      return onConfirmationDevice(state, pdu);
    case 'awaitingRandomDevice':
      return onRandomDevice(state, pdu);
    case 'awaitingComplete':
      return onComplete(state, pdu);
    case 'provisioned':
    case 'unsupported':
    case 'failed':
      return { state, send: [] };
  }
}

// ===========================================================================
// Phase handlers, in wire order.
// ===========================================================================

function onCapabilities(state: AwaitingCapabilitiesState, pdu: Buffer): ProvisioningStepResult {
  const outcome = decodeOrFail(pdu);
  if ('failed' in outcome) return { state: outcome.failed, send: [] };
  const decoded = outcome.decoded;
  if (decoded.type !== 'capabilities') {
    return { state: unexpectedType('Capabilities', decoded.type), send: [] };
  }

  if ((decoded.algorithms & ALGORITHM_CMAC_AES128_BIT) === 0) {
    return {
      state: {
        phase: 'unsupported',
        reason: `device Capabilities does not offer BTM_ECDH_P256_CMAC_AES128_AES_CCM (Table 5.21 bit 0) - the only algorithm this project implements (algorithms=0x${decoded.algorithms.toString(16).padStart(4, '0')})`,
      },
      send: [],
    };
  }
  if ((decoded.oobType & OOB_ONLY_AUTHENTICATED_BIT) !== 0) {
    return {
      state: {
        phase: 'unsupported',
        reason:
          'device Capabilities requires OOB-authenticated provisioning (Table 5.23 bit 1 set); this design implements the no-OOB path only and decides later whether to add an OOB path (docs/superpowers/specs/2026-10-06-ble-mesh-provisioner-design.md)',
      },
      send: [],
    };
  }

  const capabilitiesValue = pdu.subarray(1);

  const startPdu: ProvisioningStart = {
    type: 'start',
    algorithm: ALGORITHM_CMAC_AES128,
    publicKey: PUBLIC_KEY_NOT_OOB,
    authenticationMethod: AUTHENTICATION_METHOD_NO_OOB,
    authenticationAction: 0,
    authenticationSize: 0,
  };
  const startBytes = encodeProvisioningPdu(startPdu);

  const publicKeyPdu: ProvisioningPublicKey = {
    type: 'publicKey',
    publicKeyX: Buffer.from(state.ephemeralKeyPair.publicKey.subarray(0, 32)),
    publicKeyY: Buffer.from(state.ephemeralKeyPair.publicKey.subarray(32, 64)),
  };
  const publicKeyBytes = encodeProvisioningPdu(publicKeyPdu);

  const nextState: AwaitingPublicKeyDeviceState = {
    phase: 'awaitingPublicKeyDevice',
    inviteValue: state.inviteValue,
    capabilitiesValue,
    startValue: startBytes.subarray(1),
    ephemeralKeyPair: state.ephemeralKeyPair,
    randomProvisioner: state.randomProvisioner,
    provisioningData: state.provisioningData,
  };
  return { state: nextState, send: [startBytes, publicKeyBytes] };
}

function onPublicKeyDevice(state: AwaitingPublicKeyDeviceState, pdu: Buffer): ProvisioningStepResult {
  const outcome = decodeOrFail(pdu);
  if ('failed' in outcome) return { state: outcome.failed, send: [] };
  const decoded = outcome.decoded;
  if (decoded.type !== 'publicKey') {
    return { state: unexpectedType('Public Key', decoded.type), send: [] };
  }

  const publicKeyDevice = Buffer.concat([decoded.publicKeyX, decoded.publicKeyY]);

  // Section 5.4.2.3: "When the Provisioner receives ... a public key that
  // is equal to the Provisioner public key, then provisioning shall fail."
  if (publicKeyDevice.equals(state.ephemeralKeyPair.publicKey)) {
    return {
      state: makeFailed(0x02, "device's Public Key is identical to the provisioner's own ephemeral public key (Section 5.4.2.3)"),
      send: [],
    };
  }

  let ecdhSecret: Buffer;
  try {
    ecdhSecret = sharedSecret(state.ephemeralKeyPair.privateKey, publicKeyDevice);
  } catch (err) {
    // Section 5.4.2.3: "The Provisioner and the Provisionee shall check
    // whether the public key provided by the peer device ... is valid";
    // an invalid point is foreign/peer data, not a caller mistake, so it
    // becomes a 'failed' result rather than propagating Node's own
    // exception. Any OTHER error here is this module's own caller's
    // mistake (e.g. a corrupt ephemeralKeyPair.privateKey already past
    // `beginProvisioning`'s length check) and must not be masked.
    const code = (err as NodeJS.ErrnoException).code;
    if (code === 'ERR_CRYPTO_ECDH_INVALID_PUBLIC_KEY') {
      return {
        state: makeFailed(0x02, "device's Public Key is not a valid point on P-256 (Section 5.4.2.3)"),
        send: [],
      };
    }
    throw err;
  }

  const confSalt = confirmationSalt(
    state.inviteValue,
    state.capabilitiesValue,
    state.startValue,
    state.ephemeralKeyPair.publicKey,
    publicKeyDevice,
  );
  const confKey = confirmationKey(ecdhSecret, confSalt);
  const ownConfirmation = confirmationValue(confKey, state.randomProvisioner, NO_OOB_AUTH_VALUE);

  const confirmationPdu: ProvisioningConfirmation = { type: 'confirmation', confirmation: ownConfirmation };

  // Section 5.4.2.3: "After the ECDHSecret is computed, the Provisioner
  // ... shall delete its private-public key pair" - `ephemeralKeyPair`
  // (private key included) is not carried into this next state.
  const nextState: AwaitingConfirmationDeviceState = {
    phase: 'awaitingConfirmationDevice',
    randomProvisioner: state.randomProvisioner,
    provisioningData: state.provisioningData,
    ecdhSecret,
    confirmationSaltValue: confSalt,
    confirmationKeyValue: confKey,
    ownConfirmation,
  };
  return { state: nextState, send: [encodeProvisioningPdu(confirmationPdu)] };
}

function onConfirmationDevice(state: AwaitingConfirmationDeviceState, pdu: Buffer): ProvisioningStepResult {
  const outcome = decodeOrFail(pdu);
  if ('failed' in outcome) return { state: outcome.failed, send: [] };
  const decoded = outcome.decoded;
  if (decoded.type !== 'confirmation') {
    return { state: unexpectedType('Confirmation', decoded.type), send: [] };
  }
  if (decoded.confirmation.length !== CONFIRMATION_LENGTH) {
    return {
      state: makeFailed(
        0x02,
        `device Confirmation is ${decoded.confirmation.length} bytes, expected ${CONFIRMATION_LENGTH} under BTM_ECDH_P256_CMAC_AES128_AES_CCM`,
      ),
      send: [],
    };
  }

  // Section 5.4.2.4.2: "the Provisioner ... shall compare the
  // ConfirmationProvisioner and the ConfirmationDevice values. If the
  // values are equal, the provisioning protocol shall fail" - checked
  // before anything else, see the module header's note on this.
  if (decoded.confirmation.equals(state.ownConfirmation)) {
    return {
      state: makeFailed(0x04, "device's ConfirmationDevice equals the provisioner's own ConfirmationProvisioner (Section 5.4.2.4.2)"),
      send: [],
    };
  }

  const randomPdu: ProvisioningRandom = { type: 'random', random: state.randomProvisioner };

  const nextState: AwaitingRandomDeviceState = {
    phase: 'awaitingRandomDevice',
    randomProvisioner: state.randomProvisioner,
    provisioningData: state.provisioningData,
    ecdhSecret: state.ecdhSecret,
    confirmationSaltValue: state.confirmationSaltValue,
    confirmationKeyValue: state.confirmationKeyValue,
    confirmationDevice: decoded.confirmation,
  };
  return { state: nextState, send: [encodeProvisioningPdu(randomPdu)] };
}

function onRandomDevice(state: AwaitingRandomDeviceState, pdu: Buffer): ProvisioningStepResult {
  const outcome = decodeOrFail(pdu);
  if ('failed' in outcome) return { state: outcome.failed, send: [] };
  const decoded = outcome.decoded;
  if (decoded.type !== 'random') {
    return { state: unexpectedType('Random', decoded.type), send: [] };
  }
  if (decoded.random.length !== RANDOM_LENGTH) {
    return {
      state: makeFailed(
        0x02,
        `device Random is ${decoded.random.length} bytes, expected ${RANDOM_LENGTH} under BTM_ECDH_P256_CMAC_AES128_AES_CCM`,
      ),
      send: [],
    };
  }

  // Section 5.4.2.4.2: "When the Provisioner receives the Provisioning
  // Random PDU from the Provisionee, it shall compute the
  // ConfirmationDevice value by using the received RandomDevice value. If
  // the ConfirmationDevice value received is ... not equal to the
  // computed ConfirmationDevice, the provisioning protocol shall fail."
  // THIS is the check the brief's mutation step targets: a machine that
  // accepts `decoded.random` without this comparison can never detect a
  // forged confirmation.
  const recomputedConfirmationDevice = confirmationValue(state.confirmationKeyValue, decoded.random, NO_OOB_AUTH_VALUE);
  if (!recomputedConfirmationDevice.equals(state.confirmationDevice)) {
    return {
      state: makeFailed(
        0x04,
        'ConfirmationDevice recomputed from the received RandomDevice does not match the value received earlier (Section 5.4.2.4.2: the Provisionee is not authenticated)',
      ),
      send: [],
    };
  }

  const salt = provisioningSalt(state.confirmationSaltValue, state.randomProvisioner, decoded.random);
  const sessionKeyValue = sessionKey(state.ecdhSecret, salt);
  const sessionNonceValue = sessionNonce(state.ecdhSecret, salt);
  const deviceKeyValue = deriveDeviceKey(state.ecdhSecret, salt);

  const plaintext = Buffer.concat([
    state.provisioningData.netKey,
    encodeUInt16BE(state.provisioningData.netKeyIndex),
    Buffer.from([state.provisioningData.flags]),
    encodeUInt32BE(state.provisioningData.ivIndex),
    encodeUInt16BE(state.provisioningData.unicastAddress),
  ]);
  const { ciphertext, tag } = ccmEncrypt(sessionKeyValue, sessionNonceValue, plaintext, DATA_MIC_LENGTH);
  const dataPdu: ProvisioningData = { type: 'data', encryptedProvisioningData: ciphertext, mic: tag };

  const nextState: AwaitingCompleteState = { phase: 'awaitingComplete', deviceKeyValue };
  return { state: nextState, send: [encodeProvisioningPdu(dataPdu)] };
}

function onComplete(state: AwaitingCompleteState, pdu: Buffer): ProvisioningStepResult {
  const outcome = decodeOrFail(pdu);
  if ('failed' in outcome) return { state: outcome.failed, send: [] };
  const decoded = outcome.decoded;
  if (decoded.type !== 'complete') {
    return { state: unexpectedType('Complete', decoded.type), send: [] };
  }
  return { state: { phase: 'provisioned', deviceKey: state.deviceKeyValue }, send: [] };
}
