const PUBLIC_KEY_LENGTH = 64; // Table 5.36: Public Key X (32) || Public Key Y (32).
const PRIVATE_KEY_LENGTH = 32; // P-256 scalar, matches `crypto/ecdh.ts#generateKeyPair`.
const RANDOM_LENGTH = 16; // Section 5.4.2.4.1: RandomProvisioner/RandomDevice under BTM_ECDH_P256_CMAC_AES128_AES_CCM.
const CONFIRMATION_LENGTH = 16; // Section 5.4.2.4.1: ditto, for ConfirmationProvisioner/ConfirmationDevice.
const NET_KEY_LENGTH = 16; // Table 5.47: Network Key.
const DATA_MIC_LENGTH = 8; // Section 5.4.2.5: "The size of the Provisioning Data MIC is 8 octets."
const MAX_OCTET = 0xff; // 8 bits - Attention Duration, Flags.
const MAX_KEY_INDEX = 0x0fff; // 12 bits (Section 4.3.1.1: "Global key indexes are 12 bits long").

/** Table 5.29: the only algorithm `provisioning/crypto.ts` implements. */
const ALGORITHM_CMAC_AES128 = 0x00;
/** Table 5.21 bit 0 (Provisioning Capabilities' Algorithms field): BTM_ECDH_P256_CMAC_AES128_AES_CCM support. */
const ALGORITHM_CMAC_AES128_BIT = 0x0001;
/** Table 5.30: Public Key field value for "no OOB public key" - this design never uses an OOB-retrieved device public key. */
const PUBLIC_KEY_NOT_OOB = 0x00;
/** Table 5.31: Authentication Method value for "No OOB" - the only method this module uses. */
const AUTHENTICATION_METHOD_NO_OOB = 0x00;
/** Table 5.23 bit 1 (Provisioning Capabilities' OOB Type field): "Only OOB authenticated provisioning supported". */
const OOB_ONLY_AUTHENTICATED_BIT = 0x02;

/**
 * Section 5.4.2.4.1, "Authentication with No OOB": "the authentication
 * value shall be set to 0x00000000000000000000000000000000, which means
 * it is not authenticated" - the fixed AuthValue this module always uses,
 * since it implements the no-OOB path only.
 */
const NO_OOB_AUTH_VALUE = Buffer.alloc(16, 0);

/** Table 5.41 "Provisioning error codes", transcribed in full. */
const PROVISIONING_ERROR_NAMES: ReadonlyMap<number, string> = new Map([
  [0x00, 'Prohibited'],
  [0x01, 'Invalid PDU'],
  [0x02, 'Invalid Format'],
  [0x03, 'Unexpected PDU'],
  [0x04, 'Confirmation Failed'],
  [0x05, 'Out of Resources'],
  [0x06, 'Decryption Failed'],
  [0x07, 'Unexpected Error'],
  [0x08, 'Cannot Assign Addresses'],
  [0x09, 'Invalid Data'],
]);

/**
 * Table 5.41's own `Name` column for `errorCode` - `'RFU'` for 0x0A-0xFF
 * ("Reserved for Future Use", Table 5.41's own row for that whole range),
 * `'Unknown'` only for a value outside the single octet the Error Code
 * field actually has (`decodeProvisioningPdu` already guarantees this
 * never happens for a decoded Failed PDU, since it reads exactly one
 * octet; this module's OWN `errorCode` values, 0x00-0x09, are always
 * covered directly by the map above).
 */
export function provisioningErrorName(errorCode: number): string {
  const known = PROVISIONING_ERROR_NAMES.get(errorCode);
  if (known !== undefined) return known;
  return errorCode >= 0x0a && errorCode <= 0xff ? 'RFU' : 'Unknown';
}

